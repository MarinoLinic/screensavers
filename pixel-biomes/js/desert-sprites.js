// Hand-painted colour clusters. Every animal faces right; "." is air.
// Walking poses exchange only the feet, keeping fur and shell markings steady.
const ink = '#513d43';
const eye = '#241e29';
const glint = '#fff5d7';

function layered(palette, width, height, poses) {
  const frames = poses.map(layers => {
    const pixels = Array.from({ length: height }, () => Array(width).fill('.'));
    for (const { x, y, rows } of layers) {
      rows.forEach((row, v) => {
        [...row].forEach((pixel, u) => {
          if (pixel !== '.' && pixels[y + v]?.[x + u] !== undefined) {
            pixels[y + v][x + u] = pixel;
          }
        });
      });
    }
    return pixels.map(row => row.join(''));
  });
  return { palette, rows: frames[0], frames };
}

function walking(palette, body, feet) {
  const frames = feet.map(pose => [...body, ...pose]);
  return { palette, rows: frames[0], frames };
}

